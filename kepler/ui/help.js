const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const itemHtml = ([keys, text]) => (keys
  ? `<li><b class="help-key">${esc(keys)}</b><span>${esc(text)}</span></li>`
  : `<li class="help-note"><span>${esc(text)}</span></li>`);

export function helpHtml(sections = HELP_SECTIONS) {
  return sections.map((s) => `<section class="help-sec help-${s.id}"><h4>${esc(s.title)}</h4><ul>${s.items.map(itemHtml).join('')}</ul></section>`).join('');
}

// Короткий список для панели «Свойства»: главное из мыши и клавиш.
const SHORT = {
  mouse: ['ЛКМ', 'ПКМ, колесо нажато, пробел', 'Колесо'],
  keys: ['Ctrl+Z / Ctrl+Shift+Z', 'Ctrl+C / Ctrl+V', 'R', 'Del, Backspace', 'Стрелки', 'PgUp / PgDn', '? или F1'],
};

export function hotkeysHtml() {
  const items = HELP_SECTIONS
    .filter((s) => SHORT[s.id])
    .flatMap((s) => s.items.filter(([k]) => SHORT[s.id].includes(k)));
  return `<ul class="hotkeys">${items.map(([k, t]) => `<li><b>${esc(k)}</b> — ${esc(t)}</li>`).join('')}</ul>`;
}

export const isHelpOpen = () => !el('helpScreen').hidden;

export function openHelp() {
  const grid = el('helpGrid');
  if (grid && !grid.childElementCount) grid.innerHTML = helpHtml();
  el('helpScreen').hidden = false;
}

export function closeHelp() {
  el('helpScreen').hidden = true;
}

export function bindHelp() {
  el('helpBtn').addEventListener('click', openHelp);
  el('helpClose').addEventListener('click', closeHelp);
  el('helpScreen').addEventListener('click', (e) => { if (e.target.id === 'helpScreen') closeHelp(); });
}
