// Подсказки для телефона (core/touch-text.js): клик → тап, клавиши убраны,
// «Esc — выход» → «Готово», «Ctrl+Z» → «⟲», текст без клавиш — как был.
import test from 'node:test';
import assert from 'node:assert/strict';
import { touchText } from '../core/touch-text.js';

const TOOL = { tool: true, finish: false };
const WALL = { tool: true, finish: true };

test('дверь и окно: без «Пробела» и «Esc», выход — «Готово»', () => {
  assert.equal(touchText('Кликайте по стенам — можно ставить несколько дверей · Пробел — петли / направление · Esc — выход', TOOL),
    'Тапайте по стенам — можно ставить несколько дверей · «Готово» — выход');
  assert.equal(touchText('Кликайте по наружным стенам — можно ставить несколько окон · Esc — выход', TOOL),
    'Тапайте по наружным стенам — можно ставить несколько окон · «Готово» — выход');
});

test('стена: начало и конец цепочки', () => {
  assert.equal(touchText('Стена: кликните начало оси · Shift — без привязки · Esc — отмена', WALL), 'Стена: тапните начало оси');
  assert.equal(touchText('Стена: кликните конец (цепочка продолжится) · двойной клик, Enter или Esc — закончить', WALL),
    'Стена: тапните конец (цепочка продолжится) · «Готово» — закончить');
});

test('«Enter — готово» обещает «Готово», только если она заканчивает', () => {
  const t = 'Разрез: кликайте точки линии · Enter или двойной клик — готово · Backspace — убрать точку · Shift — без привязки · Esc — отмена';
  assert.equal(touchText(t, TOOL), 'Разрез: тапайте точки линии');
  assert.equal(touchText(t, WALL), 'Разрез: тапайте точки линии · «Готово» — закончить');
});

test('модификаторы внутри частей и скобок убираются, остальное остаётся', () => {
  assert.equal(touchText('Масса: клик — угол основания · Shift — без привязки, Ctrl — квадрат · Esc — выйти', TOOL),
    'Масса: тап — угол основания · «Готово» — выйти');
  assert.equal(touchText('Крыша: клик по помещению — накрыть · Shift+клик — добавить к выбранной · клик по крыше — выбрать · Esc — выйти', TOOL),
    'Крыша: тап по помещению — накрыть · тап по крыше — выбрать · «Готово» — выйти');
  assert.equal(touchText('Крыша: протяните прямоугольник, клик мимо помещений или Alt+клик — контур по точкам · Shift — без привязки · Esc — выйти', TOOL),
    'Крыша: протяните прямоугольник, тап мимо помещений — контур по точкам · «Готово» — выйти');
  assert.equal(touchText('Разрез: кликните с той стороны, куда смотреть (или Enter) · Esc — отмена', TOOL), 'Разрез: тапните с той стороны, куда смотреть');
  assert.equal(touchText('вершины — свободно (Alt — прямые углы) · двойной клик по вершине — удалить · K — новая крыша', TOOL), 'вершины — свободно');
  assert.equal(touchText('Разрезов нет: инструмент «Разрез» (S) на плане этажа', {}), 'Разрезов нет: инструмент «Разрез» на плане этажа');
  assert.equal(touchText('Клик — новая отметка (в метрах, например 123.45) · тяните точку — переместить · Delete — удалить · Esc — выйти', TOOL),
    'Тап — новая отметка (в метрах, например 123.45) · тяните точку — переместить · «Готово» — выйти');
});

test('размещение: «Двигайте по плану и кликните» → «Тапните на плане»', () => {
  assert.equal(touchText('Двигайте по плану и кликните, чтобы поставить «Диван» · Пробел — повернуть · Esc — отмена', TOOL),
    'Тапните на плане, чтобы поставить «Диван»');
  assert.equal(touchText('Кликните на участке — «Сосна»; повторные клики — ещё · Пробел — повернуть · Esc — выйти', TOOL),
    'Тапните на участке — «Сосна»; повторные тапы — ещё · «Готово» — выйти');
  assert.equal(touchText('Дверь поставлена · кликайте дальше или Esc', TOOL), 'Дверь поставлена · тапайте дальше');
});

test('предложения через точку: «Esc — выйти» в конце', () => {
  assert.equal(touchText('Правка: граница. Тяните точки/объект. Esc — выйти', TOOL), 'Правка: граница. Тяните точки/объект. «Готово» — выйти');
  assert.equal(touchText('Ведите вдоль стены и нажмите — стена разделится. Цифры — точный размер, Esc — отмена', TOOL),
    'Ведите вдоль стены и нажмите — стена разделится');
});

test('без инструмента «Esc — выйти» не превращается в «Готово»', () => {
  assert.equal(touchText('Фасад Юг · Esc — назад к листу 3', {}), 'Фасад Юг');
  assert.equal(touchText('Кликните — новый дом · Esc — выйти', {}), 'Тапните — новый дом');
  assert.equal(touchText('Клик по замечанию — выбрать объект. Esc или клик мимо — закрыть', {}), 'Тап по замечанию — выбрать объект. тап мимо — закрыть');
});

test('сообщения: Ctrl+Z → ⟲, Ctrl+V убирается', () => {
  assert.equal(touchText('Стена удалена вместе с её проёмами · Ctrl+Z — вернуть', {}), 'Стена удалена вместе с её проёмами · ⟲ — вернуть');
  assert.equal(touchText('Отметки высот удалены (отмена — Ctrl+Z)', {}), 'Отметки высот удалены (отмена — ⟲)');
  assert.equal(touchText('Новый проект. Прежний можно вернуть через Ctrl+Z', {}), 'Новый проект. Прежний можно вернуть через ⟲');
  assert.equal(touchText('Объект скопирован · Ctrl+V — вставить', {}), 'Объект скопирован');
  assert.equal(touchText('Скопировано — Ctrl+V вставит рядом', {}), 'Скопировано');
  assert.equal(touchText('Разрез 1 создан · двойной клик по линии или пункт в «Видах» — открыть', {}), 'Разрез 1 создан');
});

test('3D: колесо → два пальца; поле числа без «Enter/Esc»', () => {
  assert.equal(touchText('Клик — выбрать стену, помещение, проём или мебель (и на плане) · тянуть — вращать, колесо — масштаб', {}),
    'Тап — выбрать стену, помещение, проём или мебель (и на плане) · тянуть — вращать, два пальца — масштаб');
  assert.equal(touchText('Высота, мм — Enter применить, Esc отмена', TOOL), 'Высота, мм');
});

test('текст без клавиш и кликов не меняется; только клавиши — остаётся как был', () => {
  for (const t of ['Масса: тап выше основания — высота по пальцу', 'Граница участка: 378.0 м²', 'Отклик сервера', '']) {
    assert.equal(touchText(t, TOOL), t);
  }
  assert.equal(touchText('Сначала выберите объект и нажмите Ctrl+C', {}), 'Сначала выберите объект и нажмите Ctrl+C');
});
